alter table public.profiles enable row level security;
alter table public.rendiciones enable row level security;
alter table public.rendicion_items enable row level security;

drop policy if exists "profiles_select_own_or_approver" on public.profiles;
drop policy if exists "profiles_upsert_own" on public.profiles;
drop policy if exists "profiles_update_own" on public.profiles;
drop policy if exists "profiles_update_own_or_admin" on public.profiles;
drop policy if exists "rendiciones_select" on public.rendiciones;
drop policy if exists "rendiciones_insert_own" on public.rendiciones;
drop policy if exists "rendiciones_update_approver" on public.rendiciones;
drop policy if exists "items_select" on public.rendicion_items;
drop policy if exists "items_insert_own" on public.rendicion_items;
drop policy if exists "items_update_approver" on public.rendicion_items;
drop policy if exists "comprobantes_insert_own" on storage.objects;
drop policy if exists "comprobantes_select_own_or_approver" on storage.objects;

-- profiles: cada usuario ve y edita su propio perfil; aprobador/admin ven todos;
-- solo admin puede cambiar el rol de otra persona (panel "Usuarios").
create policy "profiles_select_own_or_approver" on public.profiles
  for select using (
    id = auth.uid() or public.is_admin_or_aprobador()
  );

create policy "profiles_upsert_own" on public.profiles
  for insert with check (id = auth.uid());

create policy "profiles_update_own_or_admin" on public.profiles
  for update using (id = auth.uid() or public.is_admin());

-- rendiciones: el empleado ve/crea las suyas; aprobador/admin ve y actualiza todas
create policy "rendiciones_select" on public.rendiciones
  for select using (
    empleado_id = auth.uid() or public.is_admin_or_aprobador()
  );

create policy "rendiciones_insert_own" on public.rendiciones
  for insert with check (empleado_id = auth.uid());

create policy "rendiciones_update_approver" on public.rendiciones
  for update using (
    empleado_id = auth.uid() or public.is_admin_or_aprobador()
  );

-- rendicion_items: heredan visibilidad de la rendición padre
create policy "items_select" on public.rendicion_items
  for select using (
    exists (
      select 1 from public.rendiciones r
      where r.id = rendicion_items.rendicion_id
      and (r.empleado_id = auth.uid() or public.is_admin_or_aprobador())
    )
  );

create policy "items_insert_own" on public.rendicion_items
  for insert with check (
    exists (
      select 1 from public.rendiciones r
      where r.id = rendicion_items.rendicion_id and r.empleado_id = auth.uid()
    )
  );

-- El aprobador/admin necesita poder actualizar los ítems al "Verificar en
-- contabilidad" desde la pantalla de detalle (existe_en_contabilidad, etc).
create policy "items_update_approver" on public.rendicion_items
  for update using (
    exists (
      select 1 from public.rendiciones r
      where r.id = rendicion_items.rendicion_id
      and (r.empleado_id = auth.uid() or public.is_admin_or_aprobador())
    )
  );

-- Storage policies: cada usuario sube/lee sus propios archivos (carpeta = su user id)
create policy "comprobantes_insert_own" on storage.objects
  for insert with check (
    bucket_id = 'comprobantes' and (storage.foldername(name))[1] = auth.uid()::text
  );

create policy "comprobantes_select_own_or_approver" on storage.objects
  for select using (
    bucket_id = 'comprobantes' and (
      (storage.foldername(name))[1] = auth.uid()::text or public.is_admin_or_aprobador()
    )
  );

-- ============================================================
-- Restricción de cuentas de gasto por usuario ("gasto directo")
-- ============================================================
-- El usuario maestro (admin) decide qué cuentas de la categoría 4.01.03.*
-- puede usar cada empleado al cargar un ítem "Gasto directo" (SinDocumento).
-- Si una persona NO tiene ninguna fila acá, no está restringida: ve todas
-- las cuentas. En cuanto tiene al menos una fila, el dropdown de la app
-- se limita a esas.
create table if not exists public.perfil_cuentas (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.profiles(id) on delete cascade,
  cuenta_cod text not null,
  cuenta_nombre text not null,
  created_at timestamptz not null default now(),
  unique (profile_id, cuenta_cod)
);

alter table public.perfil_cuentas enable row level security;

drop policy if exists "perfil_cuentas_select" on public.perfil_cuentas;
drop policy if exists "perfil_cuentas_admin_insert" on public.perfil_cuentas;
drop policy if exists "perfil_cuentas_admin_delete" on public.perfil_cuentas;

-- cada usuario ve sus propias cuentas permitidas; aprobador/admin ven todas
create policy "perfil_cuentas_select" on public.perfil_cuentas
  for select using (profile_id = auth.uid() or public.is_admin_or_aprobador());

-- solo el usuario maestro (admin) puede otorgar/quitar cuentas a otra persona
create policy "perfil_cuentas_admin_insert" on public.perfil_cuentas
  for insert with check (public.is_admin());

create policy "perfil_cuentas_admin_delete" on public.perfil_cuentas
  for delete using (public.is_admin());

-- ============================================================
-- Historial de cambios en ítems (auditoría)
-- ============================================================
-- Cuando el empleado o quien aprueba edita un ítem ya cargado (típicamente
-- para corregir la cuenta contable / Centro de Costo, o el monto), queda
-- registrado acá quién cambió qué y desde qué valor a cuál.
create table if not exists public.rendicion_items_historial (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.rendicion_items(id) on delete cascade,
  rendicion_id uuid not null references public.rendiciones(id) on delete cascade,
  usuario_id uuid not null references auth.users(id),
  usuario_nombre text,
  campo text not null,
  valor_anterior text,
  valor_nuevo text,
  created_at timestamptz not null default now()
);

alter table public.rendicion_items_historial enable row level security;

drop policy if exists "historial_select" on public.rendicion_items_historial;
drop policy if exists "historial_insert" on public.rendicion_items_historial;

create policy "historial_select" on public.rendicion_items_historial
  for select using (
    exists (
      select 1 from public.rendiciones r
      where r.id = rendicion_items_historial.rendicion_id
      and (r.empleado_id = auth.uid() or public.is_admin_or_aprobador())
    )
  );

create policy "historial_insert" on public.rendicion_items_historial
  for insert with check (usuario_id = auth.uid());

