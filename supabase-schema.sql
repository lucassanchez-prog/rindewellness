-- ============================================================
-- Funciones auxiliares (SECURITY DEFINER)
-- ============================================================
-- Necesarias para evitar recursión infinita: una policy de "profiles" que
-- hiciera "select ... from profiles" dentro de su propia condición generaba
-- el error 42P17 "infinite recursion detected in policy for relation profiles".
-- Al envolver la consulta en una función SECURITY DEFINER, esta corre con los
-- privilegios de quien la creó (bypasseando RLS internamente) y la policy que
-- la usa deja de auto-referenciarse.
create or replace function public.is_admin_or_aprobador()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.rol in ('aprobador','admin')
  );
$$;

create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.rol = 'admin'
  );
$$;

