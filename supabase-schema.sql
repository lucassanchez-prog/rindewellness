-- Perfiles de usuario (uno por persona que usa la app)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre text not null,
  rut text,
  rol text not null default 'empleado' check (rol in ('empleado','aprobador','admin')),
  empresa_default text,
  cargo text,
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists cargo text;

-- Cabecera de cada rendición
create table if not exists public.rendiciones (
  id uuid primary key default gen_random_uuid(),
  -- Número correlativo simple para identificar la rendición de un vistazo
  -- (folio N° 1, 2, 3...), aparte del uuid interno que usa la base.
  folio bigint generated by default as identity,
  created_at timestamptz not null default now(),
  empleado_id uuid not null references auth.users(id),
  empleado_nombre text not null,
  rut_empleado text,
  tipo_rendicion text not null default 'Reembolso' check (tipo_rendicion in ('Reembolso','FondoPorRendir')),
  -- Empresa (una de las ~10 SpA del grupo) a la que se contabiliza TODA la rendición.
  -- Se elige una sola vez, a nivel de cabecera (no por ítem): una persona puede
  -- hacer varias rendiciones, una por cada empresa distinta.
  empresa text,
  monto_total numeric(12,2) not null default 0,
  estado text not null default 'Pendiente' check (estado in ('Pendiente','Aprobado','Rechazado')),
  aprobador_id uuid references auth.users(id),
  aprobador_nombre text,
  fecha_aprobacion timestamptz,
  numero_comprobante_kame text,
  comentario text,
  -- Motivo que escribe el aprobador cuando rechaza la rendición. Se le
  -- muestra al empleado en la app y se le envía por correo.
  motivo_rechazo text
);

-- Líneas / ítems de cada rendición
create table if not exists public.rendicion_items (
  id uuid primary key default gen_random_uuid(),
  rendicion_id uuid not null references public.rendiciones(id) on delete cascade,
  tipo_item text not null check (tipo_item in ('ConDocumento','SinDocumento')),
  nombre_proveedor text,
  rut_proveedor text,
  -- Sin CHECK de valores acá a propósito: tuvimos un problema real de
  -- normalización Unicode (la tilde de "ó" puede guardarse en dos formas de
  -- bytes distintas que se ven idénticas mostradas en pantalla, y eso hacía
  -- fallar la restricción incluso con el valor "correcto"). Los valores
  -- válidos ya los controla el formulario (ver TIPOS_DOCUMENTO en app.js).
  tipo_documento text,
  nro_documento text,
  fecha_vencimiento date,
  cuenta_contable text,
  categoria text,
  -- Se copia acá el valor elegido en rendiciones.empresa (mismo valor para todos
  -- los ítems de una misma rendición), para simplificar reportes/exportación.
  -- Nullable porque queda seteado por la app luego de crear la fila; no se exige
  -- a nivel de constraint para no romper inserts en dos pasos.
  empresa text,
  monto numeric(12,2) not null,
  descripcion text,
  adjunto_url text,
  existe_en_contabilidad boolean,
  comprobante_contable_encontrado text
);

